#!/usr/bin/env python3
"""Generate a deterministic, spectrally high-pass 64x64 blue-noise-like tile.

This is a precomputed, uniformly rank-distributed dither tile. It is stable
between frames. Temporal jitter requires a separate history/reprojection pass.
"""
from __future__ import annotations
import argparse
import random
from pathlib import Path

N=64
SEED=0x4E535359

def generate() -> str:
    rng=random.Random(SEED)
    white=[[rng.random() for _ in range(N)] for _ in range(N)]
    weights=(1,4,6,4,1)
    blurred=[[0.0]*N for _ in range(N)]
    for y in range(N):
        for x in range(N):
            total=0.
            for j in range(-2,3):
                for i in range(-2,3):
                    total+=weights[j+2]*weights[i+2]*white[(y+j)%N][(x+i)%N]
            blurred[y][x]=total/256.
    # Remove low spatial frequencies; map high-pass field to a uniform CDF.
    high=[(white[y][x]-blurred[y][x], y*N+x)
          for y in range(N) for x in range(N)]
    high.sort()
    ranked=[0]*(N*N)
    for rank,(_,index) in enumerate(high):
        ranked[index]=int((rank+.5)*256/(N*N))
    lines=[]
    for offset in range(0,N*N,32):
        lines.append("    "+",".join(str(x) for x in ranked[offset:offset+32])+",")
    return (
        "// GENERATED by tools/dev/generate_sky_blue_noise.py.\n"
        "// Ranked, periodic, high-pass dither tile; do not alter by hand.\n"
        "#pragma once\n#include <array>\n#include <cstdint>\n"
        "namespace northstarcpp::sky_noise {\n"
        "inline constexpr std::array<std::uint8_t,4096> tile64 = {{\n"+
        "\n".join(lines)+"\n}};\n}\n"
    )

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument("--output",type=Path,required=True)
    ap.add_argument("--verify",action="store_true")
    a=ap.parse_args()
    data=generate()
    if a.verify:
        if not a.output.is_file() or a.output.read_text("utf8")!=data:
            raise SystemExit("Blue-noise tile header is out of sync")
        print("PASS sky blue-noise tile reproducibility")
        return
    a.output.parent.mkdir(parents=True,exist_ok=True)
    a.output.write_text(data,encoding="utf8")
    print("WROTE deterministic 64x64 sky blue-noise dither tile")

if __name__=="__main__":
    main()
