#!/usr/bin/env python3
"""Compile Vulkan material shaders into a checked-in text-only SPIR-V C++ header.

Usage: python tools/generate_vulkan_material_spirv.py
Requires glslc (Vulkan SDK). Never downloads compilers at build time.
"""
from __future__ import annotations

import os
import shutil
import struct
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHADERS = ROOT / "engine/northstarcpp/modules/render/vulkan"


def locate_glslc() -> str:
    compiler = shutil.which("glslc")
    if compiler:
        return compiler
    sdk = os.environ.get("VULKAN_SDK", "")
    if sdk:
        path = Path(sdk) / "Bin" / "glslc.exe"
        if path.is_file():
            return str(path)
    raise RuntimeError("glslc not found; install Vulkan SDK or set VULKAN_SDK")


def main() -> None:
    compiler = locate_glslc()
    result = [
        "#pragma once",
        "// Generated by tools/generate_vulkan_material_spirv.py from GLSL.",
        "#include <cstdint>",
        "namespace northstarcpp::render::vulkan::shaders {",
    ]
    for extension, symbol in (
        ("vert", "material_vertex"),
        ("frag", "material_fragment"),
        ("frag", "material_gbuffer_fragment"),
        ("comp", "material_skin_compute"),
        ("world.vert", "world_vertex"),
        ("world.frag", "world_fragment"),
    ):
        source = SHADERS / (
            "material_skin.comp" if extension == "comp"
            else extension if extension.startswith("world.")
            else "material." + extension
        )
        import tempfile

        with tempfile.TemporaryDirectory(prefix="northstar-vulkan-shader-") as tmp:
            output = Path(tmp) / (extension + ".spv")
            subprocess.run(
                [compiler, "-O", "--target-env=vulkan1.3",
                 *(["-DNS_GBUFFER=1"] if symbol=="material_gbuffer_fragment" else []),
                 str(source), "-o", str(output)],
                check=True,
            )
            data = output.read_bytes()
        if len(data) < 20 or len(data) % 4 != 0:
            raise RuntimeError("Invalid SPIR-V produced for " + str(source))
        words = struct.unpack("<" + "I" * (len(data) // 4), data)
        if words[0] != 0x07230203:
            raise RuntimeError("Unexpected SPIR-V magic")
        result.append("inline constexpr std::uint32_t " + symbol + "[]={")
        for start in range(0, len(words), 8):
            result.append(
                "    "
                + ",".join("0x%08xu" % word for word in words[start : start + 8])
                + ","
            )
        result.append("};")
    fragment_source = (SHADERS / "material.frag").read_text(encoding="utf-8")
    if ')NSG"' in fragment_source:
        raise RuntimeError("Invalid raw string delimiter in material fragment")
    result.append('inline constexpr char material_fragment_glsl[] = R"NSG(')
    fragment_lines = fragment_source.rstrip("\n").splitlines()
    result[-1] += fragment_lines[0]  # Raw literal begins with #version, no leading newline.
    result.extend(fragment_lines[1:])
    result.append(')NSG";')
    result.append("}")
    destination = SHADERS / "material_spirv.hpp"
    destination.write_text("\n".join(result) + "\n", encoding="utf-8")
    print("Generated:", destination)


if __name__ == "__main__":
    main()
