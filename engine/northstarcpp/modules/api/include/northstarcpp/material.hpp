// First-class NorthStarCpp material resource, resolved through engine.assets VFS.
// No Qt/editor dependency; the same material describes Editor and Player geometry.
#pragma once
#include <array>
#include <cstdint>
#include <string>
#include <vector>
#include <cstddef>
#include <functional>

namespace northstarcpp {
class AssetStore;
struct MaterialImage {
    std::uint32_t width=0,height=0;
    std::vector<std::uint8_t> rgba8;
};
struct MaterialDefinition {
    std::array<float,4> base_color{1.f,1.f,1.f,1.f};
    float roughness=0.65f;
    float metallic=0.f;
    bool unlit=false;
    // 0=opaque, 1=masked, 2=translucent.
    std::uint32_t blend_mode=0;
    float opacity=1.f;
    float alpha_cutoff=0.5f;
    // Generated by a bounded graph compiler from whitelisted nodes.
    // A blank string selects the standard PBR pipeline.
    std::string graph_shader_defines;
    // 0=Base Color, 1=Normal, 2=Roughness, 3=Metallic, 4=Emissive.
    std::array<MaterialImage,5> textures;
};
// Nodes support scalar, color, UV, texture sample, add, multiply, lerp,
 // one-minus, saturate; output expressions are compiled into HLSL defines.
std::string compile_material_graph(std::string const& graph_json);
// Resolve reusable .material-function.json sources through a read-only VFS
// callback. Dependencies are expanded and type-checked before HLSL emission;
// no file system, Qt or renderer ABI is embedded in the compiler.
using MaterialFunctionResolver=std::function<std::string(std::string const&)>;
std::string expand_material_graph_functions(
    std::string const& graph_json,MaterialFunctionResolver const& resolver);
std::string compile_material_graph_with_functions(
    std::string const& graph_json,MaterialFunctionResolver const& resolver);
// Reads project *.material.json, *.material-instance.json, compiled YMAT;
// loads referenced texture images from VFS, including common sharedAssets.
// Throws on missing, malformed, oversized or unsupported resource content.
MaterialDefinition load_material_definition(AssetStore const& assets,
                                            std::string const& reference);
} // namespace northstarcpp
